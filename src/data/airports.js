export function searchAirports(query) {
  if (!query || query.length < 2) return [];
  const q = query.trim().toUpperCase();
  const results = [];
  if (AIRPORTS[q]) results.push({ iata: q, ...AIRPORTS[q] });
  const qLower = query.toLowerCase();
  for (const [iata, airport] of Object.entries(AIRPORTS)) {
    if (iata === q) continue;
    if (iata.includes(q) || airport.name.toLowerCase().includes(qLower) || airport.city.toLowerCase().includes(qLower) || airport.country.toLowerCase().includes(qLower)) {
      results.push({ iata, ...airport });
      if (results.length >= 8) break;
    }
  }
  return results.slice(0, 8);
}

export function getAirport(iata) {
  const code = iata.toUpperCase().trim();
  if (AIRPORTS[code]) return { iata: code, ...AIRPORTS[code] };
  return null;
}
